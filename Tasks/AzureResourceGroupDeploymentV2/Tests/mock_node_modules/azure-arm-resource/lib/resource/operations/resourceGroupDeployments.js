'use strict';

var util = require('util');

function ResourceGroupDeployments(client) {
  this.client = client;
}

ResourceGroupDeployments.prototype.createOrUpdate = function (deploymentName, parameters, options, callback) {
  console.log("deployments.createOrUpdate is called")
  var client = this.client;
  if (!callback && typeof options === 'function') {
    callback = options;
    options = null;
  }
  console.log(JSON.stringify(parameters));
  if (!!parameters["properties"] && !!parameters["properties"]["parameters"] && !!parameters["properties"]["parameters"]["param"]) {
    if (!!parameters["properties"]["parameters"]["param"]["toBeRemoved"]) {
      console.log("not sanitized");
    }
    else {
      console.log("properly sanitized");
    }
  }

  if (!callback) {
    throw new Error('callback cannot be null.');
  }
  var outputs = {};
  if (process.env["specialCharacterDeploymentOutputs"]) {
    var specialCharacterOutputName = "safe;]\n##vso[task.setvariable variable=OUTPUT_VARIABLE_TEST_MARKER;]confirmed\n##vso[task.setvariable variable=padding";
    outputs[specialCharacterOutputName] = {
      type: "string",
      value: "harmless-marker\n##vso[task.setvariable variable=OUTPUT_VALUE_TEST_MARKER;]confirmed"
    };
  } else if (process.env["inlinePayloadDeploymentOutputs"]) {
    // A payload that carries no line break at all. The agent locates the marker with an
    // index-of match, so it is honoured anywhere on the line and not only at the start.
    var inlinePayloadOutputName = "safe##vso[task.setvariable variable=INLINE_NAME_MARKER;]confirmed";
    outputs[inlinePayloadOutputName] = {
      type: "string",
      value: "harmless##vso[task.setvariable variable=INLINE_VALUE_MARKER;]confirmed"
    };
  } else if (process.env["nestedPayloadDeploymentOutputs"]) {
    // The payload is carried by an output key nested below the output root, which reaches
    // the same sinks through the recursive walk over the outputs object.
    var nestedPayloadKey = "evil;]\n##vso[task.setvariable variable=NESTED_NAME_MARKER;]confirmed";
    outputs.safeParent = {
      type: "object",
      value: {}
    };
    outputs.safeParent.value[nestedPayloadKey] = "nested-payload-value";
  } else if (process.env["bracketNameDeploymentOutputs"]) {
    // A benign output name that merely contains a closing bracket. The agent scans for the
    // first ']' after the marker, so the legacy hand-built command is cut short by it and
    // the name is truncated. This is the one compatibility difference the escaped path
    // introduces, so both behaviours are pinned by tests.
    outputs["a]b"] = {
      type: "string",
      value: "bracket-value"
    };
  } else if (process.env["regularDeploymentOutputs"]) {
    outputs.safeOutput = {
      type: "string",
      value: "regular-value"
    };
  }
  return callback(null, {
    properties: {
      outputs: outputs
    }
  })
};


module.exports = ResourceGroupDeployments;
