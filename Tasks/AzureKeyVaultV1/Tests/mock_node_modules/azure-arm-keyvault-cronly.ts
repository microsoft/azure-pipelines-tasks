'use strict';

// Bare CR with no LF anywhere, immediately followed by a forged "##vso[" prefix - exercises the
// CR-only routing (KeyVault.ts's `hasBareCrOnly`) for MSRC case 169467.
const crOnlySecretValue = "secretpart\r##vso[task.setvariable variable=BASH_ENV]/tmp/evil.sh";

class CrOnlyKeyVaultClient {
    private credentials;
    private subscriptionId;
    private keyVaultName;
    private keyVaultUrl;

    constructor(credentials, subscriptionId, keyVaultName, keyVaultUrl) {
        this.credentials = credentials;
        this.subscriptionId = subscriptionId;
        this.keyVaultName = keyVaultName;
        this.keyVaultUrl = keyVaultUrl;
    }

    getSecrets = function (nextLink, callback) {
        if (!callback) {
            throw new Error('callback cannot be null.');
        }

        let secrets = [
            {
                name: "crOnlySecret",
                enabled: true,
                expires: null,
                contentType: "secret"
            }
        ];
        callback(null, secrets);
    };

    getSecretValue = function (secretName, callback) {
        if (!callback) {
            throw new Error('callback cannot be null.');
        }
        if (secretName === null || secretName === undefined || typeof secretName.valueOf() !== 'string') {
            throw new Error('secretName cannot be null or undefined and it must be of type string.');
        }

        callback(null, crOnlySecretValue);
    };
}

exports.KeyVaultClient = CrOnlyKeyVaultClient;
exports.secretValue = crOnlySecretValue;
