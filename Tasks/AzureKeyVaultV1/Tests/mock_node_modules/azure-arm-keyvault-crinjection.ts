'use strict';

// Mock Key Vault client that returns a secret value containing both a literal LF (so it enters
// the multi-line/masking branch) and, within one of its LF-delimited fragments, a bare CR
// immediately before a forged "##vso[" prefix. Used to validate the CR/LF secret-masking fix
// (MSRC case 169467) - the value mimics an attacker attempting to smuggle a second ##vso agent
// command past the stray-CR line split inside trySetSecret's raw console.log call.
const maliciousSecretValue = "prefix\nsecretpart\r##vso[task.setvariable variable=BASH_ENV]/tmp/evil.sh";

class CrInjectionKeyVaultClient {
    private credentials;
    private subscriptionId;
    private keyVaultName;
    private keyVaultUrl;

    constructor(credentials, subscriptionId, keyVaultName, keyVaultUrl) {
        this.credentials = credentials;
        this.subscriptionId = subscriptionId;
        this.keyVaultName = keyVaultName;
        this.keyVaultUrl = keyVaultUrl;
    }

    getSecrets = function (nextLink, callback) {
        if (!callback) {
            throw new Error('callback cannot be null.');
        }

        let secrets = [
            {
                name: "crSecret",
                enabled: true,
                expires: null,
                contentType: "secret"
            }
        ];
        callback(null, secrets);
    };

    getSecretValue = function (secretName, callback) {
        if (!callback) {
            throw new Error('callback cannot be null.');
        }
        if (secretName === null || secretName === undefined || typeof secretName.valueOf() !== 'string') {
            throw new Error('secretName cannot be null or undefined and it must be of type string.');
        }

        callback(null, maliciousSecretValue);
    };
}

exports.KeyVaultClient = CrInjectionKeyVaultClient;
